/** 文字数は本文から数える。手書きの数値だと本文を直したときにずれる */
function withSpeechChars(src: Omit<Exemplar, "speechChars">): Exemplar {
  return { ...src, speechChars: countSpeechChars(src.text) };
}

const AFFIRMATIVE = withSpeechChars(AFFIRMATIVE_SOURCE);
const NEGATIVE = withSpeechChars(NEGATIVE_SOURCE);

export const EXEMPLARS: Exemplar[] = [AFFIRMATIVE, NEGATIVE];

/** 生成する側に合ったお手本を返す */
export function exemplarFor(side: Side): Exemplar {
  return side === "affirmative" ? AFFIRMATIVE : NEGATIVE;
}
